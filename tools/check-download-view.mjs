import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'../frontend');
const {default:ts}=await import(pathToFileURL(path.join(root,'node_modules/typescript/lib/typescript.js')));
const code=ts.transpileModule(await fs.readFile(path.join(root,'src/downloadView.ts'),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {downloadRows,downloadPage}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const jobs=Object.freeze(Array.from({length:5000},(_,i)=>Object.freeze({id:String(i),kind:i%2?'quark':'lanzou',status:i%3?'saved':'failed',input:Object.freeze({name:`文件${i}.zip`}),destination:`C:/备份/${i}.zip`})));
assert.equal(downloadRows(jobs,'all','','','newest')[0].id,'4999');
assert.equal(downloadRows(jobs,'all','','','oldest')[0].id,'0');
assert.equal(downloadRows(jobs,'all','','','name')[2].id,'2');
assert.equal(downloadRows(jobs,'all','','','attention')[0].status,'failed');
assert.deepEqual(downloadRows(jobs,'failed','quark',' 备份/3.zip ','newest').map(j=>j.id),['3']);
assert.equal(downloadRows(jobs,'all','','文件10.zip','newest').length,1);
assert.equal(downloadPage(jobs,100,50).items[0].id,'4950');
assert.equal(downloadPage(jobs,999,50).page,100);
assert.equal(downloadPage(jobs,-2,50).page,1);
assert.equal(downloadPage(jobs,NaN,999).pageSize,50);
assert.deepEqual(downloadPage([],9,25),{page:1,pages:1,pageSize:25,first:0,last:0,items:[]});
assert.equal(downloadPage(jobs.slice(0,51),2,50).items.length,1);
assert.equal(jobs[0].id,'0');assert.equal(jobs[4999].id,'4999');
console.log('PASS: 5000-job filtering/sorting, path search, immutable source, bounded pages, last/empty/invalid page boundaries.');
